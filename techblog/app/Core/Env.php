<?php
declare(strict_types=1);

namespace App\Core;

/** Minimal .env reader/writer (KEY=value, optional quotes, # comments). */
final class Env
{
    /** @var array<string,string> */
    private static array $vars = [];

    public static function load(string $file): bool
    {
        if (!is_file($file) || !is_readable($file)) {
            return false;
        }
        foreach (file($file, FILE_IGNORE_NEW_LINES | FILE_SKIP_EMPTY_LINES) ?: [] as $line) {
            $line = trim($line);
            if ($line === '' || $line[0] === '#' || !str_contains($line, '=')) {
                continue;
            }
            [$k, $v] = explode('=', $line, 2);
            $k = trim($k);
            $v = trim($v);
            if (strlen($v) >= 2 && ($v[0] === '"' || $v[0] === "'") && $v[-1] === $v[0]) {
                $v = stripcslashes(substr($v, 1, -1));
            }
            self::$vars[$k] = $v;
        }
        return true;
    }

    public static function get(string $key, mixed $default = null): mixed
    {
        if (!array_key_exists($key, self::$vars)) {
            return $default;
        }
        $v = self::$vars[$key];
        return match (strtolower($v)) {
            'true' => true,
            'false' => false,
            default => $v,
        };
    }

    /** @param array<string,string|bool|int> $values */
    public static function write(string $file, array $values): bool
    {
        $out = "# Generated by the installer on " . date('c') . "\n# Keep this file private. Never commit it.\n";
        foreach ($values as $k => $v) {
            if (is_bool($v)) {
                $v = $v ? 'true' : 'false';
            }
            $v = (string)$v;
            $out .= $k . '="' . addcslashes($v, "\"\\\n\r") . "\"\n";
        }
        $ok = file_put_contents($file, $out, LOCK_EX) !== false;
        if ($ok) {
            @chmod($file, 0600);
        }
        return $ok;
    }
}
